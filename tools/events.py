#!/usr/bin/env python3
"""Catalogue of _events bits: every data reference (KNPC/RESID appear conditions, gift triggers,
dialogue branches, world-map entrances) plus constant SetBit/FindBit/ClearBit calls in the decompiles.
usage: events.py ORIGDIR DECOMPDIR > docs/events.md"""
import os, re, sys, glob, struct
from collections import defaultdict
sys.path.insert(0, os.path.dirname(__file__))
from loc import load_loc
from locdump import cstrings, recs
import talkdump, convdump

def main(src, decomp):
    refs = defaultdict(list); npcname = {}
    names = convdump.item_names(src)
    for path in sorted(glob.glob(os.path.join(src, 'D[0-9][0-9].MCV'))):
        L = load_loc(path); d = L['raw']; p = L['ptr']
        if not (p['maps'] and len(L['locname']) >= 3 and all(c.isalnum() or c in " .'" for c in L['locname'])): continue
        fn = os.path.basename(path)[:3]; loc = f"{fn} {L['locname'].strip()}"
        ends = sorted(set(v for v in p.values() if v)) + [len(d)]
        end = lambda k: next((e for e in ends if e > p[k]), len(d))
        words = cstrings(d, p['gwrds'], end('gwrds')) if p['gwrds'] else []
        nm = lambda i: words[i] if i < len(words) else f'?{i}'
        for r in recs(d, p['knpcptr'], 10):
            if r[8]: refs[r[8]].append(f'{loc}: NPC {r[4]} {nm(r[5])} appears only if set')
            if r[9]: refs[r[9]].append(f'{loc}: NPC {r[4]} {nm(r[5])} appears only if clear')
        if p['resids'] and p['resids'] != p['roomptr']:
            for i, r in enumerate(recs(d, p['resids'], 6, (end('resids') - p['resids']) // 6)):
                if r[4]: refs[r[4]].append(f'{loc}: resident {nm(r[0])} (room {i}) only if set')
                if r[5]: refs[r[5]].append(f'{loc}: resident {nm(r[0])} (room {i}) only if clear')
        if p['locevptr'] and p['locevptr'] != p['roomptr'] and fn == 'D01':
            o = p['locevptr']; n = 0
            while o < end('locevptr'):
                grp = []
                while o < end('locevptr') and d[o] != 0xff: grp.append(d[o]); o += 1
                o += 1
                for e in grp: refs[e].append(f'world map: entrance {n} shown when set')
                n += 1
        for r in recs(d, p['knpcptr'], 10):
            if 0 < r[4] < 0xfa: npcname.setdefault(r[4], nm(r[5]))
        if p['resids'] and p['resids'] != p['roomptr']:
            for r in recs(d, p['resids'], 6, (end('resids') - p['resids']) // 6):
                if 0 < r[1] < 0xfa: npcname.setdefault(r[1], nm(r[0]))
    for n in range(24 * 8):
        s, ctexts, cwords = talkdump.conv(src, n)
        for w, lines in talkdump.decode(s, cwords, ctexts):
            for l in lines:
                m = re.match(r'  unless event (\d+) is set: (.*)', l)
                if m: refs[int(m[1])].append(f'dialogue: NPC {n} {npcname.get(n, "")} "{w}" → while clear: "{m[2][:60]}"')
    for f in sorted(glob.glob(os.path.join(src, 'C[0-9][0-9].MCV'))):
        d = open(f, 'rb').read(); p = struct.unpack('<42H', d[:0x54]); base = int(os.path.basename(f)[1:3]) * 8
        for n in range(8):
            o = p[18 + n]
            while d[o] != 0xff and o + 5 <= len(d):
                it, mn, m1, m2, ev = d[o:o + 5]
                refs[ev].append(f'gift: NPC {base + n} given {mn}× {names.get(it, hex(it))} → set'); o += 5
    for f in sorted(glob.glob(os.path.join(decomp, '*.c'))):
        src_c = open(f).read(); ov = os.path.basename(f)[:-2]
        for m in re.finditer(r'(SetBit|ClearBit|FindBit)\(&G_events,(0x[0-9a-f]+|\d+)\)', src_c):
            v = int(m[2], 0); refs[v].append(f'code {ov}: {m[1]}')
        for m in re.finditer(r'G_events(?:\+(\d+))? (\||&|=)[^;\n]*?(0x[0-9a-f]+)', src_c):
            byte = int(m[1] or 0); mask = int(m[3], 16)
            if mask & 0xff != mask or mask == 0: continue
            for b in range(8):
                if mask >> b & 1: refs[byte * 8 + b].append(f'code {ov}: {"set" if m[2] == "|" else "test"} (byte {byte} mask {mask:#x})')
    print('# Event bits (`_events`)\n\nGenerated by `tools/events.py`. Bit → every data/code reference found. Dialogue lines are what the NPC says while the bit is **clear**.\n')
    for e in sorted(refs):
        print(f'## {e}')
        for r in sorted(set(refs[e])): print(f'- {r}')
        print()

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
