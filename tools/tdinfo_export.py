"""Export TDInfo-derived docs: docs/symbols.txt, docs/structs.h, ghidra/symbols.tsv"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
import tdinfo
exe = sys.argv[1]
r = tdinfo.parse(exe)
n = tdinfo.export_symbols(r, 'ghidra/symbols.tsv', 'docs/symbols.txt')
open('docs/structs.h', 'w').write(f'/* Struct/union/enum definitions recovered from TDInfo {r["version"]} in MC2.EXE.\n   Member offsets assume byte packing (Borland default). Generated by tools/tdinfo_export.py */\n\n' + tdinfo.export_structs(exe))
print('symbols', n, 'structs lines', len(open('docs/structs.h').read().splitlines()))
